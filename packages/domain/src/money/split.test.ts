describe('split sum invariants', () => {
  it('holds for a seeded sweep of 1000 valid orders', () => {
    // Numerical Recipes LCG, modulus 2^32. Prices are at or above the minimum
    // for their cost. Amounts stay small so the documented fee formula is
    // exact. The sum identities alone would accept an all-zero split, so the
    // sweep also checks the field definitions and a non-negative margin.
    const seeds = buildLcgSeeds(
      SWEEP_ORDER_COUNT * SWEEP_SEEDS_PER_ORDER,
      SWEEP_SEED,
    )
    const orders = buildSweepOrders(seeds)
    expect(orders).toHaveLength(SWEEP_ORDER_COUNT)
    orders.forEach((lines) => {
      expect(lines.length).toBeGreaterThan(0)
      lines.forEach((line) => {
        expect(line.unitPriceCents).toBeGreaterThanOrEqual(
          minUnitPriceCents(line.unitCogsCents),
        )
      })
      const subtotalCents = lines.reduce(
        (sum, line) => sum + line.quantity * line.unitPriceCents,
        0,
      )
      const cogsCents = lines.reduce(
        (sum, line) => sum + line.quantity * line.unitCogsCents,
        0,
      )
      const split = computeSplit(lines)
      const fields = [
        split.subtotalCents,
        split.platformFeeCents,
        split.totalCents,
        split.cogsCents,
        split.providerMarginCents,
      ]
      fields.forEach((field) => {
        expect(Number.isSafeInteger(field)).toBe(true)
        expect(field).toBeGreaterThanOrEqual(0)
      })
      expect(split.subtotalCents).toBe(subtotalCents)
      expect(split.cogsCents).toBe(cogsCents)
      expect(split.totalCents).toBe(subtotalCents)
      expect(split.platformFeeCents).toBe(
        Math.floor((subtotalCents * 75 + 9999) / 10000),
      )
      expect(split.providerMarginCents).toBe(
        subtotalCents - cogsCents - split.platformFeeCents,
      )
      expect(split.providerMarginCents).toBeGreaterThanOrEqual(0)
      expect(
        split.cogsCents + split.providerMarginCents + split.platformFeeCents,
      ).toBe(split.totalCents)
    })
  })
})
