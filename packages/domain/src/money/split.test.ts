// Revision 2: the patient pays the subtotal. The fee comes out of the markup.
// totalCents === subtotalCents, and providerMarginCents = subtotal - cogs - fee.
// Revision 7 fee oracle: Math.floor((subtotalCents * 75 + 9999) / 10000).
// That ceilings 75 bps to the next cent. Reference rows are hand-checked
// against that formula, not generated by it.

// minUnitPriceCents is a revision 2 export. Reading it off the module keeps
// this file typechecking until the export exists. A missing export fails.
interface MinUnitPriceCents {
  (unitCogsCents: number): number
}

type ExpectedSplitCode = SplitErrorCode | 'PRICE_BELOW_MINIMUM'

