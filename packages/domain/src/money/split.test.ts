const SWEEP_ORDER_COUNT = 1000
const SWEEP_SEED = 0xc0ffee
const SWEEP_SEEDS_PER_ORDER = 12
const LCG_MULTIPLIER = 1664525
const LCG_INCREMENT = 1013904223

function minUnitPriceCents(unitCogsCents: number): number {
  const exported: unknown = Reflect.get(splitModule, 'minUnitPriceCents')
  if (typeof exported !== 'function') {
    throw new Error('minUnitPriceCents is not exported from ./split')
  }
  const fn = exported as MinUnitPriceCents
  return fn(unitCogsCents)
}

function ceilUnitFeeCents(priceCents: number): number {
  return Math.floor((priceCents * 75 + 9_999) / 10_000)
}

function thrownBy(run: () => void): unknown {
  try {
    run()
  } catch (caught: unknown) {
    return caught
  }
  return undefined
}

function expectSplitError(
  lines: readonly SplitLine[],
  code: ExpectedSplitCode,
  lineIndex: number | undefined,
): void {
  const thrown = thrownBy(() => {
    computeSplit(lines)
  })
  expect(thrown).toBeInstanceOf(Error)
  expect(thrown).toBeInstanceOf(SplitValidationError)
  if (!(thrown instanceof SplitValidationError)) {
    return
  }
  expect(thrown.name).toBe('SplitValidationError')
  const actual: string = thrown.code
  expect(actual).toBe(code)
  expect(thrown.lineIndex).toBe(lineIndex)
}

function expectMinimumRejected(unitCogsCents: number): void {
  const thrown = thrownBy(() => {
    minUnitPriceCents(unitCogsCents)
  })
  expect(thrown).toBeInstanceOf(Error)
  expect(thrown).toBeInstanceOf(SplitValidationError)
  if (!(thrown instanceof SplitValidationError)) {
    return
  }
  expect(thrown.name).toBe('SplitValidationError')
  expect(thrown.code).toBe('INVALID_AMOUNT')
  expect(thrown.lineIndex).toBeUndefined()
}

function expectFeeRejected(subtotalCents: number): void {
  const thrown = thrownBy(() => {
    computePlatformFee(subtotalCents)
  })
  expect(thrown).toBeInstanceOf(Error)
  expect(thrown).toBeInstanceOf(SplitValidationError)
  if (!(thrown instanceof SplitValidationError)) {
    return
  }
  expect(thrown.name).toBe('SplitValidationError')
  expect(thrown.code).toBe('INVALID_AMOUNT')
  // Not a line-scoped input, so the optional line index is absent.
  expect(thrown.lineIndex).toBeUndefined()
}

function expectOrder(lines: readonly SplitLine[], expected: OrderSplit): void {
  expect(computeSplit(lines)).toEqual(expected)
}

function nextLcg(seed: number): number {
  return (Math.imul(LCG_MULTIPLIER, seed) + LCG_INCREMENT) >>> 0
}

function seedAt(seeds: readonly number[], index: number): number {
  const value = seeds[index]
  if (value === undefined) {
    throw new Error(`No seed at index ${index}`)
  }
  return value
}

function buildLcgSeeds(count: number, seed: number): number[] {
  return Array.from({ length: count }).reduce<number[]>(
    (seeds, _slot, index) => {
      const previous = index === 0 ? seed : seedAt(seeds, index - 1)
      return [...seeds, nextLcg(previous)]
    },
    [],
  )
}

function buildSweepOrders(seeds: readonly number[]): SplitLine[][] {
  return Array.from({ length: SWEEP_ORDER_COUNT }, (_order, orderIndex) => {
    const offset = orderIndex * SWEEP_SEEDS_PER_ORDER
    const lineCount = (seedAt(seeds, offset) % 3) + 1
    return Array.from({ length: lineCount }, (_line, lineIndex) => {
      const base = offset + 1 + lineIndex * 3
      const quantity = (seedAt(seeds, base) % 5) + 1
      const unitCogsCents = seedAt(seeds, base + 1) % 50_000
      const unitPriceCents =
        minUnitPriceCents(unitCogsCents) + (seedAt(seeds, base + 2) % 50_000)
      return { quantity, unitPriceCents, unitCogsCents }
    })
  })
}

describe('computePlatformFee', () => {
  it('exports the platform fee as 75 basis points', () => {
    expect(PLATFORM_FEE_BPS).toBe(75)
  })

  it.each(FEE_REFERENCE)(
    'charges $feeCents cents on a $subtotalCents cent subtotal',
    ({ subtotalCents, feeCents }) => {
      expect(computePlatformFee(subtotalCents)).toBe(feeCents)
    },
  )

  it.each(FEE_EXACT_HALF_UP)(
    'rounds up, including an exact half cent ($subtotalCents -> $feeCents)',
    ({ subtotalCents, feeCents }) => {
      expect(computePlatformFee(subtotalCents)).toBe(feeCents)
    },
  )

  it.each(FEE_LARGE)(
    'charges $feeCents cents on large subtotal $subtotalCents',
    ({ subtotalCents, feeCents }) => {
      expect(computePlatformFee(subtotalCents)).toBe(feeCents)
    },
  )

  it.each<number>(FEE_REJECTED)(
    'rejects non-integer or negative subtotal %s',
    (subtotalCents) => {
      expectFeeRejected(subtotalCents)
    },
  )
})

describe('minUnitPriceCents', () => {
  it.each<MinPriceCase>(MIN_PRICE_REFERENCE)(
    'cost $unitCogsCents requires at least $minUnitPriceCents',
    ({ unitCogsCents, minUnitPriceCents: priceCents }) => {
      // Smallest p >= cost whose markup covers ceil(p * 75 / 10000).
      const actual = minUnitPriceCents(unitCogsCents)
      expect(actual).toBe(priceCents)
      expect(actual).toBeGreaterThanOrEqual(unitCogsCents)
      expect(actual - unitCogsCents).toBeGreaterThanOrEqual(
        ceilUnitFeeCents(actual),
      )
      if (actual === 0) {
        return
      }
      const below = actual - 1
      const belowCovers =
        below >= unitCogsCents &&
        below - unitCogsCents >= ceilUnitFeeCents(below)
      expect(belowCovers).toBe(false)
    },
  )

  it.each<number>(FEE_REJECTED)(
    'rejects non-integer or negative cost %s',
    (unitCogsCents) => {
      expectMinimumRejected(unitCogsCents)
    },
  )

  it('equates the markup on the minimum price with the fee, including cost 581', () => {
    expect(IDENTITY_COSTS).toContain(581)
    const mismatches = IDENTITY_COSTS.filter((cost) => {
      const price = minUnitPriceCents(cost)
      return price - cost !== computePlatformFee(price)
    })
    expect(mismatches).toEqual([])
  })
})

describe('computeSplit', () => {
  it('splits a single line', () => {
    expectOrder([{ quantity: 1, unitPriceCents: 2500, unitCogsCents: 1000 }], {
      subtotalCents: 2500,
      platformFeeCents: 19,
      totalCents: 2500,
      cogsCents: 1000,
      providerMarginCents: 1481,
    })
  })

  it('sums multiple lines before charging the fee', () => {
    expectOrder(
      [
        { quantity: 1, unitPriceCents: 5000, unitCogsCents: 2000 },
        { quantity: 1, unitPriceCents: 3000, unitCogsCents: 1000 },
      ],
      {
        subtotalCents: 8000,
        platformFeeCents: 60,
        totalCents: 8000,
        cogsCents: 3000,
        providerMarginCents: 4940,
      },
    )
  })

  it('extends a line by quantity before splitting', () => {
    expectOrder([{ quantity: 3, unitPriceCents: 500, unitCogsCents: 200 }], {
      subtotalCents: 1500,
      platformFeeCents: 11,
      totalCents: 1500,
      cogsCents: 600,
      providerMarginCents: 889,
    })
  })

  it('returns a zero margin when the markup equals the fee', () => {
    // Cost 66, price 67: markup is 1 and the fee on 67 cents is 1.
    expectOrder([{ quantity: 1, unitPriceCents: 67, unitCogsCents: 66 }], {
      subtotalCents: 67,
      platformFeeCents: 1,
      totalCents: 67,
      cogsCents: 66,
      providerMarginCents: 0,
    })
  })

  it('keeps a non-negative margin at the minimum price for cost 7000', () => {
    expectOrder([{ quantity: 1, unitPriceCents: 7053, unitCogsCents: 7000 }], {
      subtotalCents: 7053,
      platformFeeCents: 53,
      totalCents: 7053,
      cogsCents: 7000,
      providerMarginCents: 0,
    })
  })

  it('allows a zero price when cost is zero', () => {
    expectOrder([{ quantity: 1, unitPriceCents: 0, unitCogsCents: 0 }], {
      subtotalCents: 0,
      platformFeeCents: 0,
      totalCents: 0,
      cogsCents: 0,
      providerMarginCents: 0,
    })
  })

  it('rejects two lines priced at cost 66', () => {
    // Half-up per unit would allow price 66. Two of those lines have subtotal
    // 132, fee 1, and margin -1. The rounded-up minimum is 67, so line 0 fails
    // before that negative margin can be stored.
    expectSplitError(
      [
        { quantity: 1, unitPriceCents: 66, unitCogsCents: 66 },
        { quantity: 1, unitPriceCents: 66, unitCogsCents: 66 },
      ],
      'PRICE_BELOW_MINIMUM',
      0,
    )
  })

  it('accepts two lines priced at 67 when cost is 66', () => {
    // Markup is 1 on each line. Subtotal 134 rounds up to a 2 cent fee, so
    // the provider margin is 0.
    expectOrder(
      [
        { quantity: 1, unitPriceCents: 67, unitCogsCents: 66 },
        { quantity: 1, unitPriceCents: 67, unitCogsCents: 66 },
      ],
      {
        subtotalCents: 134,
        platformFeeCents: 2,
        totalCents: 134,
        cogsCents: 132,
        providerMarginCents: 0,
      },
    )
  })

  // One unit: subtotal $120.00, fee $0.90 taken from the markup, patient pays
  // $120.00. Wholesale cost $70.00, provider margin $49.10.
  it('takes the $0.90 fee out of the $120.00 price', () => {
    expectOrder([{ quantity: 1, unitPriceCents: 12000, unitCogsCents: 7000 }], {
      subtotalCents: 12000,
      platformFeeCents: 90,
      totalCents: 12000,
      cogsCents: 7000,
      providerMarginCents: 4910,
    })
  })

  it('charges the fee on the order subtotal, not the sum of per-line fees', () => {
    // Each 1 cent line rounds up to its own 1 cent fee, so the per-line sum
    // is 2. The order subtotal is 2 cents, which rounds up to 1. The order
    // fee is never above that per-line sum.
    const lines: readonly SplitLine[] = [
      { quantity: 1, unitPriceCents: 1, unitCogsCents: 0 },
      { quantity: 1, unitPriceCents: 1, unitCogsCents: 0 },
    ]
    const perLineFeeSum = lines
      .map((line) =>
        Math.floor((line.quantity * line.unitPriceCents * 75 + 9999) / 10000),
      )
      .reduce((sum, fee) => sum + fee, 0)
    expect(perLineFeeSum).toBe(2)
    expectOrder(lines, {
      subtotalCents: 2,
      platformFeeCents: 1,
      totalCents: 2,
      cogsCents: 0,
      providerMarginCents: 1,
    })
    expect(computeSplit(lines).platformFeeCents).toBeLessThan(perLineFeeSum)
  })

  it('does not depend on line order', () => {
    const first: SplitLine = {
      quantity: 2,
      unitPriceCents: 67,
      unitCogsCents: 10,
    }
    const second: SplitLine = {
      quantity: 1,
      unitPriceCents: 12000,
      unitCogsCents: 7000,
    }
    const third: SplitLine = {
      quantity: 4,
      unitPriceCents: 300,
      unitCogsCents: 250,
    }
    const lines: readonly SplitLine[] = [first, second, third]
    const orders = [
      lines,
      Array.from(lines).reverse(),
      [second, third, first],
      [third, first, second],
    ]
    const splits = orders.map((order) => computeSplit(order))
    splits.forEach((split) => {
      expect(split).toEqual(splits[0])
    })
  })

  it('accepts the largest subtotal the documented fee formula can compute exactly', () => {
    expectOrder(
      [
        {
          quantity: 1,
          unitPriceCents: LARGEST_EXACT_FEE_SUBTOTAL,
          unitCogsCents: 0,
        },
      ],
      {
        subtotalCents: LARGEST_EXACT_FEE_SUBTOTAL,
        platformFeeCents: LARGEST_EXACT_FEE_CENTS,
        totalCents: LARGEST_EXACT_FEE_SUBTOTAL,
        cogsCents: 0,
        providerMarginCents:
          LARGEST_EXACT_FEE_SUBTOTAL - LARGEST_EXACT_FEE_CENTS,
      },
    )
  })

  it('accepts one line whose own fee intermediate is still exact', () => {
    expectOrder(
      [{ quantity: 1, unitPriceCents: FEE_SAFE_LINE_CENTS, unitCogsCents: 0 }],
      {
        subtotalCents: FEE_SAFE_LINE_CENTS,
        platformFeeCents: FEE_SAFE_LINE_FEE_CENTS,
        totalCents: FEE_SAFE_LINE_CENTS,
        cogsCents: 0,
        providerMarginCents: FEE_SAFE_LINE_CENTS - FEE_SAFE_LINE_FEE_CENTS,
      },
    )
  })
})

